/**
 * Система обучающих подсказок (ТЗ §31.6): при наведении на метрику появляется
 * пояснение — что это, как формируется (словами, без формул) и на что влияет.
 *
 * Принцип: каждая подсказка отвечает на 3 вопроса:
 *   1) что это за показатель;
 *   2) из чего он складывается (бытовым языком);
 *   3) почему он важен и что с ним делать.
 */
'use client';

import type { ReactNode } from 'react';
import { HoverCard, HoverCardContent, HoverCardTrigger } from '@/components/ui/hover-card';
import { Info } from 'lucide-react';
import { cn } from '@/lib/utils';

export interface HintContent {
  title: string;
  body: string;
  advice?: string;
}

/** Маленькая иконка «i»: при наведении/тапе открывает карточку-подсказку. */
export function InfoHint({
  hint,
  icon: Icon = Info,
  className,
}: {
  hint: HintContent | string;
  icon?: typeof Info;
  className?: string;
}) {
  const content: HintContent =
    typeof hint === 'string' ? { title: '', body: hint } : hint;
  return (
    <HoverCard openDelay={100} closeDelay={150}>
      <HoverCardTrigger asChild>
        <button
          type="button"
          aria-label={`Подсказка: ${content.title}`}
          className={cn(
            'inline-flex h-5 w-5 shrink-0 items-center justify-center rounded-full text-stone-400 transition-colors hover:bg-amber-100 hover:text-amber-700 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-amber-400',
            className,
          )}
        >
          <Icon className="h-3.5 w-3.5" aria-hidden />
        </button>
      </HoverCardTrigger>
      <HoverCardContent
        side="top"
        align="start"
        className="w-80 max-w-[85vw] border-amber-200 bg-white p-0 shadow-lg"
      >
        <div className="rounded-lg">
          {content.title && (
            <p className="text-sm font-semibold text-stone-900 px-3.5 pt-3">{content.title}</p>
          )}
          <p className="text-xs leading-relaxed text-stone-600 px-3.5 py-2.5">{content.body}</p>
          {content.advice && (
            <div className="flex gap-2 rounded-b-lg border-t border-amber-100 bg-amber-50/60 px-3.5 py-2.5">
              <span aria-hidden>💡</span>
              <p className="text-xs leading-relaxed text-amber-900">{content.advice}</p>
            </div>
          )}
        </div>
      </HoverCardContent>
    </HoverCard>
  );
}

/** Инлайн-подсказка для строк таблиц и списков: текст + иконка. */
export function HintedLabel({
  label,
  hint,
  className,
}: {
  label: ReactNode;
  hint: HintContent | string;
  className?: string;
}) {
  return (
    <span className={cn('inline-flex items-center gap-1', className)}>
      <span>{label}</span>
      <InfoHint hint={hint} />
    </span>
  );
}

