/** Месяц игрового дня (день года 0..363 → месяц 1..12). */
export function monthOfDay(dayIdx: number): number {
  return Math.min(12, Math.floor(dayIdx / 30.4) + 1);
}

export function dayOfYear(week: number, day: number): number {
  return (week - 1) * 7 + day;
}
