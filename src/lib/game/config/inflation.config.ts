/**
 * ИНФЛЯЦИЯ (БАЛ-v2 §10, запрос пользователя): три независимых процесса.
 *
 *   FoodIdx  — закупочные цены ингредиентов растут ~+10%/год
 *   WageIdx  — оклады индексируются ~+12,5%/год (шаг раз в квартал)
 *   UtilIdx  — коммунальные ~+17,5%/год (поверх сезонного множителя)
 *
 * Цены меню НЕ индексируются автоматически — эрозия маржи при бездействии:
 * кто не переоценивает меню, теряет 2–4 п.п. маржи за год. Перекладывание
 * в цены возвращает почти всё, но требует действия игрока.
 *
 * Шаг — раз в квартал (12 недель), детерминированные константы, без ГСЧ:
 * движковые эталоны воспроизводимы байт-в-байт.
 */

export interface InflationConfig {
  /** Годовой рост закупочных цен, доли (запрос: 8–12%). */
  foodAnnual: number;
  /** Годовая индексация окладов, доли (запрос: 10–15%). */
  wageAnnual: number;
  /** Годовой рост коммунальных, доли (запрос: 15–20%). */
  utilAnnual: number;
  /** Шаг индексации — раз в N недель (квартал игры = 12 недель). */
  stepWeeks: number;
}

export const INFLATION: InflationConfig = {
  foodAnnual: 0.1, // +10%/год → ×1,024 за квартал, за год ×1,10
  wageAnnual: 0.125, // +12,5%/год → ×1,030 за квартал, за год ×1,126
  utilAnnual: 0.175, // +17,5%/год → ×1,041 за квартал, за год ×1,177
  stepWeeks: 12,
};

/** Квартальный множитель закупочных цен. */
export const FOOD_STEP = Math.pow(1 + INFLATION.foodAnnual, INFLATION.stepWeeks / 52);
/** Квартальный множитель окладов. */
export const WAGE_STEP = Math.pow(1 + INFLATION.wageAnnual, INFLATION.stepWeeks / 52);
/** Квартальный множитель коммунальных. */
export const UTIL_STEP = Math.pow(1 + INFLATION.utilAnnual, INFLATION.stepWeeks / 52);

/**
 * ПЕРЕРАБОТКИ (БАЛ-v2 §5.2): ФОТ растёт вместе с загрузкой — «маржа-храповик»
 * выключен. При загрузке станций свыше порога команда задерживается на смене:
 *   Overload = max(0, пиковая загрузка худшей станции недели − threshold)
 *   OvertimeCostWeek = γ × Overload × WeeklyGross, кап от ФОТ
 * Транзакция «overtime» — «Сверхурочные (ТК РФ, ×1,5 после 8 ч)».
 * Побочно: в перегрузочные дни усталость копится быстрее (+20%, запрос).
 */
export const OVERTIME = {
  /** Загрузка станции, с которой начинаются переработки. */
  threshold: 0.9,
  /** γ: доля недельного ФОТ (gross) за каждый пункт перегруза свыше порога. */
  gamma: 0.25,
  /** Кап переработок от недельного ФОТ. */
  capShare: 0.08,
  /** Ускорение прироста усталости в перегрузочные дни. */
  fatigueBoost: 1.2,
} as const;
